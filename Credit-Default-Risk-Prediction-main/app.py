import streamlit as st
import pandas as pd
import joblib

model = joblib.load("credit_risk_model.pkl")

st.set_page_config(page_title="Credit Risk Predictor", page_icon="🏦", layout="wide")

st.title("🏦 Credit Default Risk Prediction")
st.caption("Machine Learning powered borrower risk assessment")

st.subheader("Borrower Information")

col1, col2 = st.columns(2)

with col1:
    age = st.number_input("Age", 18, 69, 30)
    income = st.number_input("Annual Income (₹)", 15000, 150000, 50000)
    loan_amount = st.number_input("Loan Amount (₹)", 5000, 250000, 50000)

with col2:
    credit_score = st.number_input("Credit Score", 300, 849, 600)
    months_employed = st.number_input("Months Employed", 0, 119, 24)
    dti_ratio = st.slider("Debt-to-Income Ratio", 0.10, 0.90, 0.30, 0.01)

if st.button("Predict Loan Risk", type="primary", use_container_width=True):

    input_data = pd.DataFrame([{
        "Age": age,
        "Income": income,
        "LoanAmount": loan_amount,
        "CreditScore": credit_score,
        "MonthsEmployed": months_employed,
        "DTIRatio": dti_ratio
    }])

    probability = model.predict_proba(input_data)[0][1]
    prediction = model.predict(input_data)[0]

    st.divider()
    st.subheader("Prediction Result")

    st.metric("Estimated Default Probability", f"{probability * 100:.2f}%")

    if probability < 0.30:
        st.success("LOW RISK")
    elif probability < 0.60:
        st.warning("MEDIUM RISK")
    else:
        st.error("HIGH RISK")

    if prediction == 1:
        st.error("Model Prediction: Potential Default")
    else:
        st.success("Model Prediction: Non-Default")

    st.progress(float(probability))

    st.info(
        "This prediction is generated by a machine learning model "
        "and should not be used as the sole basis for real lending decisions."
    )
